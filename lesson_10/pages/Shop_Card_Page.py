from selenium.webdriver.common.by import By


class CartPage:
    """
    Page Object Model для страницы корзины интернет-магазина.

    Предоставляет методы для взаимодействия с элементами страницы корзины,
    включая оформление заказа и управление товарами в корзине.

    """

    def __init__(self, driver) -> None:
        """
        Инициализация страницы корзины.

        Сохраняет экземпляр WebDriver и инициализирует локаторы
        для элементов на странице корзины.

        """
        self.driver = driver
        self.checkout_button = (By.ID, "checkout")

    def checkout(self) -> None:

        """
        Оформляет заказ путем нажатия на кнопку оформления заказа.

        Находит кнопку оформления заказа на странице корзины по ID "checkout"
        и выполняет клик по ней. После нажатия обычно происходит переход
        на страницу оформления заказа или оплаты.

        """

        self.driver.find_element(*self.checkout_button).click()
